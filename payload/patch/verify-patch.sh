#!/bin/sh
# no-verify patch (2026-11-07)
# Purpose: neutralize the ISO signature verifier inside the live overlay so the
# installer's "Verify ISO" page returns instantly. Nothing else is touched.
set +e
for r in /root /; do
    d="$r/usr/bin"
    [ -d "$d" ] || continue
    [ -w "$d" ] || mount -o remount,rw "$r"
    [ -w "$d" ] || continue
    printf '#!/bin/sh\nexit 0\n' > "$d/deepin-iso-verify" && chmod 755 "$d/deepin-iso-verify"
done
exit 0
